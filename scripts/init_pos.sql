-- init_pos.sql — Seeds POS transactions from the Brigade Bangalore dataset.
-- Runs automatically on first postgres container start via docker-entrypoint-initdb.d

CREATE TABLE IF NOT EXISTS pos_transactions (
    id               SERIAL PRIMARY KEY,
    store_id         VARCHAR(64)  NOT NULL,
    transaction_id   VARCHAR(64)  NOT NULL,
    timestamp        TIMESTAMPTZ  NOT NULL,
    basket_value_inr FLOAT        NOT NULL DEFAULT 0.0,
    CONSTRAINT uq_pos_txn_id UNIQUE (transaction_id)
);

CREATE INDEX IF NOT EXISTS ix_pos_store_ts ON pos_transactions (store_id, timestamp);

